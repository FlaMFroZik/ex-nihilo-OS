#ifndef EXEC_H
#define EXEC_H

#include <stdint.h>

/* ================================================================
 * exec — загрузчик бинарников и kexecve().
 *
 * Поддерживаемый формат: ELF32 (little-endian, i386, ET_EXEC).
 * PT_LOAD-сегменты копируются по их виртуальным адресам (модель
 * памяти плоская, страничной адресации нет — vaddr == физический),
 * хвост p_memsz > p_filesz обнуляется (bss), точка входа — e_entry.
 * На новом стеке программы строится классический кадр i386:
 *   [argc][argv[0]]...[NULL][envp[0]]...[NULL], строки — выше.
 *
 * Успешный kexecve() НЕ возвращается: exec_jump() делает iret
 * сразу на e_entry в Ring 3 (образ вызывающего заменён). Ошибка
 * (нет файла, не ELF, плохой сегмент) — отрицательный код, и
 * вызывающий продолжает жить, как в POSIX.
 * ================================================================ */

/* Переход Ring0 -> Ring3 на уже загруженный образ (syscall.asm).
 * Не возвращается. */
__attribute__((noreturn)) void exec_jump(uint32_t entry, uint32_t user_esp);

/* Освободить страницу стека последнего exec'а (после SYS_KEXIT). */
void kexec_cleanup(void);

#endif
