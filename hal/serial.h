#ifndef SERIAL_H
#define SERIAL_H

/* COM1 (0x3F8): посимвольный вывод для отладки.
 *
 * Зачем в ядре: экран ограничен по размеру (48 строк в 1024x768), а
 * отчёт длиннее — верх уходит при прокрутке. Через COM1 можно снять
 * весь вывод целиком: в QEMU это `-serial stdio`, в тестах — эмулятор.
 * Плата за это — несколько десятков строк кода и пара портов.
 */

/* Настроить COM1: 115200 бод, 8N1, без прерываний. */
void serial_init(void);

/* Отправить один символ (перевод строки превращается в CR LF). */
void serial_putc(char c);

/* Отправить строку. */
void serial_write(const char *s);

#endif
