#ifndef VIDEO_H
#define VIDEO_H

#include <stdint.h>

/* Вывод текста в графическом режиме VBE с ROM-шрифтом 8x16.
 *
 * Зачем: в текстовом режиме 80x25 помещается 25 строк, а отчёт ядра
 * длиннее — верх приходится прокручивать. В 1024x768 при шрифте 8x16
 * получается 128 строк по 48 символов, и отчёт виден целиком.
 *
 * Режим ставит загрузчик (boot2.asm, setup_video): ядро уже работает в
 * защищённом режиме, где INT 10h недоступен. Загрузчик передаёт через
 * общую область (VIDEO_INFO_ADDR = 0x0900) размеры кадра, шаг строки,
 * физический адрес линейного буфера и указатель на копию ROM-шрифта.
 *
 * Если графический режим установить не удалось (нет VBE, нет
 * подходящего режима), драйвер откатывается на текстовый буфер
 * 0xB8000 — вывод продолжает работать, просто в 80x25.
 */

#define VIDEO_GLYPH_W   8
#define VIDEO_GLYPH_H   16
#define VIDEO_FG        0x00C0C0C0u     /* светло-серый, 0x00RRGGBB */

/* Инициализация: разобрать параметры, оставленные загрузчиком.
 * Возвращает 1, если графический режим активен, 0 — текстовый. */
int video_init(void);

/* Размеры экрана в символах. */
unsigned int video_cols(void);
unsigned int video_rows(void);

/* Очистить экран цветом фона. */
void video_clear(void);

/* Прокрутить содержимое на одну текстовую строку вверх. */
void video_scroll(void);

/* Нарисовать символ c в позиции (row, col). */
void video_putc(unsigned int row, unsigned int col, char c);

/* Режим, выбранный при инициализации: 1 — графический VBE, 0 — текст. */
int video_is_graphics(void);

/* Параметры кадра для отчёта: ширина, высота, бит на пиксель. */
unsigned int video_width(void);
unsigned int video_height(void);
unsigned int video_bpp(void);

#endif
