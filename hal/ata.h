#ifndef ATA_H
#define ATA_H

#include <stdint.h>
#include "fs/blockdev.h"

/* Драйвер ATA PIO (LBA28) для primary master.
 *
 * Нужен файловой системе: в защищённом режиме INT 13h недоступен
 * (BIOS работает только в реальном режиме), поэтому читать и писать
 * секторы ядро обязано само.
 *
 * Выбран PIO, а не DMA: PIO — это несколько out/in на порты 0x1F0..0x1F7
 * плюс REP INSW/OUTSW, без таблиц PRDT и без физических адресов под
 * выравнивание. Для 16 МиБ образа скорость не имеет значения.
 *
 * Почему HDD, а не дискета: у контроллера флоппи (FDC) запись требует
 * настройки канала DMA, моторов и таймингов — на порядок больше кода и
 * источников ошибок ради того же результата.
 */

#define ATA_PRIMARY_IO   0x1F0
#define ATA_PRIMARY_CTRL 0x3F6
#define ATA_SECTOR_SIZE  512

/* С какого сектора образа начинается FAT16. Секторы 0..63 отведены
 * загрузчику (0..2) и ядру; 64 — начало раздела с файловой системой.
 * Должно совпадать с FAT_BASE_LBA в Makefile и с tools/mkfatimg.py. */
#define EXNIHILO_FAT_LBA 64

/* Инициализация: определить наличие диска. 1 — диск есть, 0 — нет. */
int ata_init(void);

/* Сколько секторов у диска (LBA28), 0 — неизвестно/нет диска. */
uint32_t ata_sectors(void);

/* Подготовить blockdev для FAT16. Возвращает 0 при успехе. */
int ata_blockdev(blockdev_t *dev);

/* Низкоуровневые операции ровно с одним сектором.
 *
 * ОБЯЗАТЕЛЬНО объявлены здесь: без прототипа компилятор не знает
 * cdecl-сигнатуру и передаёт первый аргумент в EAX вместо стека —
 * драйвер читал бы не тот сектор. */
int ata_read_sector(uint32_t lba, void *buf);
int ata_write_sector(uint32_t lba, const void *buf);

/* Сколько секторов драйвер прочитал и записал с момента загрузки. */
uint32_t ata_read_count(void);
uint32_t ata_write_count(void);

#endif
